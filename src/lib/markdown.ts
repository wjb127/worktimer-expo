// AI 응답 마크다운 제거(감사 #12) — RN Text는 평문 렌더라 **굵게**·## 헤더가 그대로 보임.
// 서버 프롬프트가 평문을 지시하지만, 기존 저장 메시지와 LLM 이탈까지 방어하는 표시 직전 정리.
// (codex: 링크·인라인코드·인용·취소선까지 커버)
export function stripMarkdown(text: string): string {
  return text
    .replace(/\*\*(.+?)\*\*/g, '$1') // **굵게**
    .replace(/__(.+?)__/g, '$1') // __굵게__
    .replace(/~~(.+?)~~/g, '$1') // ~~취소선~~
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1') // [텍스트](링크) → 텍스트
    .replace(/`([^`]+)`/g, '$1') // `인라인 코드`
    .replace(/(^|\n)#{1,6}\s+/g, '$1') // # ~ ###### 헤더
    .replace(/(^|\n)>\s?/g, '$1') // > 인용
    .replace(/(^|\n)\s*[-*]\s+/g, '$1· '); // - 리스트 → ·
}
